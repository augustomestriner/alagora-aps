import {test,expect} from '@playwright/test';

test('desktop, filtros e telas móveis sem transbordamento',async({page})=>{
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/');
  await expect(page.getByText(/^(Tempo real|Conectado)$/)).toBeVisible();
  await expect(page.getByRole('heading',{name:'De olho na cidade.'})).toBeVisible();
  await expect.poll(()=>page.locator('.report-card').count()).toBeGreaterThanOrEqual(3);
  await page.screenshot({path:'test-results/desktop.png',fullPage:true});
  await page.getByLabel('Filtrar gravidade').selectOption('high');
  await expect(page.locator('.report-card .badge.high').first()).toBeVisible();
  expect(await page.locator('.report-card .badge:not(.high)').count()).toBe(0);
  await page.getByLabel('Filtrar gravidade').selectOption('');
  await page.getByLabel('Filtrar situação').selectOption('resolved');
  await expect(page.locator('.report-card .status-text.resolved').first()).toBeVisible();
  expect(await page.locator('.report-card .status-text:not(.resolved)').count()).toBe(0);
  await page.getByLabel('Filtrar situação').selectOption('open');
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('.bottom-nav')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Mapa',exact:true}).click();
  await expect(page.locator('.map-panel')).toBeVisible();
  await page.screenshot({path:'test-results/mobile-map.png',fullPage:true});
});

test('login, registro com foto, histórico, sincronização entre clientes e fila offline',async({browser})=>{
  const context=await browser.newContext({viewport:{width:1366,height:960}});const page=await context.newPage();
  const other=await browser.newContext({viewport:{width:390,height:844}});const observer=await other.newPage();
  await page.goto('/');await observer.goto('/');
  await page.getByRole('button',{name:'Entrar na conta',exact:true}).click();
  await page.getByRole('button',{name:'Preencher acesso de teste'}).click();
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'Registrar ocorrência',exact:true}).click();
  const title=`Teste interface ${Date.now()}`;
  await page.getByLabel('Título da ocorrência',{exact:true}).fill(title);
  await page.getByLabel('Endereço ou referência').fill('Rua de teste · Jundiaí');
  await page.getByLabel('Descreva a situação').fill('Registro automatizado de validação do aplicativo.');
  await page.getByLabel('Latitude',{exact:true}).fill('-23.198');
  const photo=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=32;c.height=32;const ctx=c.getContext('2d')!;ctx.fillStyle='#123d35';ctx.fillRect(0,0,32,32);return c.toDataURL('image/png').split(',')[1];});
  await page.getByLabel('Adicionar foto',{exact:true}).setInputFiles({name:'teste.png',mimeType:'image/png',buffer:Buffer.from(photo,'base64')});
  await expect(page.getByAltText('Prévia da foto da ocorrência')).toBeVisible();
  await page.screenshot({path:'test-results/create.png',fullPage:true});
  await page.getByRole('button',{name:'Compartilhar ocorrência',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Buscar por local ou ocorrência').fill(title);
  await expect(page.locator('.report-card')).toHaveCount(1);
  // O segundo cliente recebe o registro pela consulta periódica, sem recarregar.
  await observer.getByLabel('Buscar por local ou ocorrência').fill(title);
  await expect(observer.locator('.report-card')).toHaveCount(1,{timeout:20000});
  await page.locator('.report-card').click();
  await expect(page.getByRole('heading',{name:'Histórico de acompanhamento'})).toBeVisible();
  await expect(page.getByAltText('Foto enviada pelo autor da ocorrência')).toBeVisible();
  await page.getByLabel('Nova situação').selectOption('resolved');
  await page.getByLabel('O que mudou?').fill('Água escoou e a ocorrência foi encerrada no teste.');
  await page.getByRole('button',{name:'Salvar atualização',exact:true}).click();
  await expect(page.locator('.timeline li')).toHaveCount(2);
  await page.getByRole('button',{name:'Fechar',exact:true}).click();
  await expect(observer.locator('.report-card')).toHaveCount(0,{timeout:20000});
  await page.getByLabel('Buscar por local ou ocorrência').fill('');
  await page.getByRole('button',{name:'Registrar ocorrência',exact:true}).click();
  const queued=`Registro offline ${Date.now()}`;
  await page.getByLabel('Título da ocorrência',{exact:true}).fill(queued);
  await page.getByLabel('Endereço ou referência').fill('Rua offline · Jundiaí');
  await page.getByLabel('Descreva a situação').fill('Deve ser guardado e enviado ao restabelecer a conexão.');
  await page.getByLabel('Latitude',{exact:true}).fill('-23.191');
  await context.setOffline(true);
  await page.getByRole('button',{name:'Compartilhar ocorrência',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:/Meus registros/}).first().click();
  await expect(page.locator('.pending-row')).toHaveCount(1);
  await page.screenshot({path:'test-results/offline.png',fullPage:true});
  await context.setOffline(false);
  await expect(page.locator('.pending-row')).toHaveCount(0,{timeout:30000});
  await page.getByLabel('Buscar por local ou ocorrência').fill(queued);
  await expect(page.locator('.report-card')).toHaveCount(1);
  await context.close();await other.close();
});
